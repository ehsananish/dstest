package ir.ehsananish.dstest.ds

import android.content.Context
import android.media.AudioAttributes
import android.media.AudioFocusRequest
import android.media.AudioManager
import android.media.MediaPlayer
import androidx.compose.runtime.Composable
import androidx.compose.runtime.DisposableEffect
import androidx.compose.runtime.remember
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.platform.LocalLifecycleOwner
import androidx.lifecycle.Lifecycle
import androidx.lifecycle.LifecycleEventObserver

/*
 * Voice guide for onboarding: assets/voice/onboarding_1.mp3, onboarding_2.mp3, ... (one per page).
 * Generated by `factory.py voice <slug>` from apps/<slug>/voice.txt. Without the files nothing plays
 * and the speaker controls are hidden.
 *
 * Behaviour (after user feedback on the voice guide):
 * - Never starts on its own while the phone is on silent/vibrate; it plays only if the user asks
 *   (speaker or replay button), so the app does not suddenly talk in a quiet place.
 * - Requests transient audio focus (other audio ducks instead of mixing at full volume) and pauses
 *   when another app or a call takes the focus.
 * - Starts only after a page has settled (not mid-swipe), pauses when the app goes to background and
 *   continues where it left off when the user returns.
 */

private val speechAttributes: AudioAttributes = AudioAttributes.Builder()
    .setUsage(AudioAttributes.USAGE_MEDIA)
    .setContentType(AudioAttributes.CONTENT_TYPE_SPEECH)
    .build()

@Composable
fun rememberHasVoiceGuide(): Boolean {
    val ctx = LocalContext.current
    return remember {
        runCatching { ctx.assets.list("voice")?.any { it.startsWith("onboarding_") } == true }.getOrDefault(false)
    }
}

/** True when the ringer is on silent or vibrate: the guide must not start by itself then. */
fun isPhoneSilenced(ctx: Context): Boolean = runCatching {
    val am = ctx.getSystemService(Context.AUDIO_SERVICE) as AudioManager
    am.ringerMode != AudioManager.RINGER_MODE_NORMAL
}.getOrDefault(false)

/**
 * Plays the narration of onboarding page [page] (0-based) while [enabled]; stops on page change.
 * [userRequested] means the user explicitly asked for audio (then silent mode is not a reason to stay
 * quiet). Changing [replayKey] restarts the current page from the beginning.
 */
@Suppress("DEPRECATION")
@Composable
fun OnboardingVoice(page: Int, enabled: Boolean, userRequested: Boolean = false, replayKey: Int = 0) {
    val ctx = LocalContext.current
    val lifecycle = LocalLifecycleOwner.current.lifecycle
    DisposableEffect(page, enabled, replayKey) {
        val allowed = enabled && (userRequested || !isPhoneSilenced(ctx))
        val am = ctx.getSystemService(Context.AUDIO_SERVICE) as? AudioManager
        var player: MediaPlayer? = null
        var focus: AudioFocusRequest? = null
        var resumeOnForeground = false

        fun abandonFocus() {
            focus?.let { f -> runCatching { am?.abandonAudioFocusRequest(f) } }
            focus = null
        }

        if (allowed) {
            player = runCatching {
                ctx.assets.openFd("voice/onboarding_${page + 1}.mp3").use { fd ->
                    MediaPlayer().apply {
                        setAudioAttributes(speechAttributes)
                        setDataSource(fd.fileDescriptor, fd.startOffset, fd.length)
                        prepare()
                    }
                }
            }.getOrNull()
            val p = player
            if (p != null) {
                val request = AudioFocusRequest.Builder(AudioManager.AUDIOFOCUS_GAIN_TRANSIENT_MAY_DUCK)
                    .setAudioAttributes(speechAttributes)
                    .setOnAudioFocusChangeListener { change ->
                        when (change) {
                            AudioManager.AUDIOFOCUS_LOSS,
                            AudioManager.AUDIOFOCUS_LOSS_TRANSIENT,
                            AudioManager.AUDIOFOCUS_LOSS_TRANSIENT_CAN_DUCK -> runCatching { if (p.isPlaying) p.pause() }
                        }
                    }
                    .build()
                val granted = am == null ||
                    runCatching { am.requestAudioFocus(request) }.getOrDefault(AudioManager.AUDIOFOCUS_REQUEST_GRANTED) ==
                    AudioManager.AUDIOFOCUS_REQUEST_GRANTED
                if (granted) {
                    focus = request
                    p.setOnCompletionListener { abandonFocus() }
                    runCatching { p.start() }
                } else {
                    p.release()
                    player = null
                }
            }
        }

        val observer = LifecycleEventObserver { _, event ->
            val p = player ?: return@LifecycleEventObserver
            when (event) {
                Lifecycle.Event.ON_PAUSE -> runCatching {
                    resumeOnForeground = p.isPlaying
                    if (p.isPlaying) p.pause()
                }
                Lifecycle.Event.ON_RESUME -> runCatching {
                    if (resumeOnForeground && enabled) p.start()
                    resumeOnForeground = false
                }
                else -> Unit
            }
        }
        lifecycle.addObserver(observer)
        onDispose {
            lifecycle.removeObserver(observer)
            runCatching { player?.stop() }
            player?.release()
            abandonFocus()
        }
    }
}
